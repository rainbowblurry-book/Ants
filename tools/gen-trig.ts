/**
 * Generates src/sim/trig.ts: a literal quarter-wave sine table at 0.1°
 * (901 entries, 0° to 90°) plus lookup helpers (DR-011, J9).
 *
 * The sim may not call Math.sin/cos at runtime, because engines are not
 * required to give identical results. This tool runs once; the output is
 * committed, and tests/trig.test.ts checks it is current.
 *
 *   node tools/gen-trig.ts          write the file
 *   node tools/gen-trig.ts --check  exit 1 if the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const TRIG_STEPS = 900; // tenths of a degree in a quarter turn

export const paths = {
  out: fileURLToPath(new URL('../src/sim/trig.ts', import.meta.url)),
};

/** sin(i · 0.1°) for i = 0..900, computed with the host Math.sin. */
export function buildTable(): number[] {
  const table: number[] = [];
  for (let i = 0; i <= TRIG_STEPS; i++) {
    table.push(Math.sin((i * Math.PI) / 1800));
  }
  // Pin the exact end points.
  table[0] = 0;
  table[TRIG_STEPS] = 1;
  return table;
}

export function buildTrigTs(table: number[] = buildTable()): string {
  const rows: string[] = [];
  for (let i = 0; i < table.length; i += 4) {
    rows.push(
      `  ${table
        .slice(i, i + 4)
        .map(String)
        .join(', ')},`,
    );
  }
  return `// GENERATED by tools/gen-trig.ts. Do not edit; run \`node tools/gen-trig.ts\`.
// Sine and cosine for integer angles in tenths of a degree (DR-011, J9).
// The table is literal so every engine reads the same bits.

/** sin(i · 0.1°) for i = 0..900. */
export const SIN_QUARTER: readonly number[] = [
${rows.join('\n')}
];

/** Tenths of a degree in a full turn. */
export const DECI_FULL = 3600;

/** Normalises any integer angle in tenths of a degree to 0..3599. */
export function normDeci(a: number): number {
  const r = a % DECI_FULL;
  return r < 0 ? r + DECI_FULL : r;
}

/** sin of an integer angle in tenths of a degree. */
export function sinDeci(a: number): number {
  if (!Number.isInteger(a)) throw new RangeError(\`sinDeci: angle \${a} is not an integer\`);
  const n = normDeci(a);
  if (n <= 900) return SIN_QUARTER[n] as number;
  if (n <= 1800) return SIN_QUARTER[1800 - n] as number;
  if (n <= 2700) return -(SIN_QUARTER[n - 1800] as number);
  return -(SIN_QUARTER[3600 - n] as number);
}

/** cos of an integer angle in tenths of a degree. */
export function cosDeci(a: number): number {
  return sinDeci(a + 900);
}
`;
}

function main(): void {
  const text = buildTrigTs();
  if (process.argv.includes('--check')) {
    if (readFileSync(paths.out, 'utf8') !== text) {
      console.error('src/sim/trig.ts is stale. Run: node tools/gen-trig.ts');
      process.exit(1);
    }
    return;
  }
  writeFileSync(paths.out, text);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
